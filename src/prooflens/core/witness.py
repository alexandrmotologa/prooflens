"""Witness and symbol table parsers and serializers for Circom / snarkjs.

The iden3 WTNS binary format:
Magic: 4 bytes b'wtns' (0x77746e73)
Version: uint32 LE (version 1 or 2)
Num sections: uint32 LE

Section 1 (Header):
- field_size: uint32 LE (32 for BN254)
- prime: field_size bytes LE
- n_witness: uint32 LE (number of witness elements)

Section 2 (Witness Data):
- n_witness field elements, each field_size bytes LE.

Symbol tables (.sym) generated by Circom:
- Comma-separated text lines: <wire_id>,<symbol_path>[,<component>]
"""

from __future__ import annotations

import io
import json
import struct
from pathlib import Path
from typing import BinaryIO, Dict, List, Optional, Union

from prooflens.core.field import BN254_PRIME, FieldElement

WTNS_MAGIC = b"wtns"
WTNS_SUPPORTED_VERSIONS = [1, 2]

SECTION_WTNS_HEADER = 1
SECTION_WTNS_DATA = 2


class Witness:
    """Container for the circuit witness vector [w_0, w_1, ..., w_{n-1}]."""

    def __init__(
        self,
        values: Optional[Dict[int, FieldElement]] = None,
        modulus: int = BN254_PRIME,
    ) -> None:
        self.modulus = modulus
        self.values: Dict[int, FieldElement] = values or {}

    def __getitem__(self, wire_id: int) -> FieldElement:
        return self.values.get(wire_id, FieldElement.zero(modulus=self.modulus))

    def __setitem__(self, wire_id: int, val: Union[FieldElement, int, str]) -> None:
        if not isinstance(val, FieldElement):
            val = FieldElement(val, modulus=self.modulus)
        self.values[wire_id] = val

    def __len__(self) -> int:
        return len(self.values)

    def __contains__(self, wire_id: int) -> bool:
        return wire_id in self.values

    def clone(self) -> Witness:
        """Create a deep copy of the witness vector."""
        return Witness(values=dict(self.values), modulus=self.modulus)

    def to_list(self) -> List[FieldElement]:
        """Convert to ordered list from 0 to max_wire_id."""
        if not self.values:
            return []
        max_id = max(self.values.keys())
        return [self.values.get(i, FieldElement.zero(modulus=self.modulus)) for i in range(max_id + 1)]

    def to_json_dict(self, symbols: Optional[Dict[int, str]] = None) -> Dict[str, str]:
        """Convert to JSON serializable dictionary with values in hex or decimal."""
        res: Dict[str, str] = {}
        for wire_id, elem in sorted(self.values.items()):
            key = symbols.get(wire_id, f"w{wire_id}") if symbols else f"{wire_id}"
            res[key] = str(elem.to_signed_int())
        return res


class WTNSBinaryParser:
    """Parser for binary Circom/snarkjs .wtns files."""

    def __init__(self, stream: BinaryIO) -> None:
        self.stream = stream

    @classmethod
    def from_file(cls, path: Union[str, Path]) -> Witness:
        with open(path, "rb") as f:
            return cls(f).parse()

    @classmethod
    def from_bytes(cls, data: bytes) -> Witness:
        return cls(io.BytesIO(data)).parse()

    def parse(self) -> Witness:
        magic = self.stream.read(4)
        if magic != WTNS_MAGIC:
            raise ValueError(f"Invalid WTNS file magic: expected {WTNS_MAGIC!r}, got {magic!r}")

        version_bytes = self.stream.read(4)
        if len(version_bytes) < 4:
            raise ValueError("Unexpected EOF reading WTNS version")
        version = struct.unpack("<I", version_bytes)[0]
        if version not in WTNS_SUPPORTED_VERSIONS:
            raise ValueError(f"Unsupported WTNS version: {version}")

        num_sections_bytes = self.stream.read(4)
        num_sections = struct.unpack("<I", num_sections_bytes)[0]

        field_size: Optional[int] = None
        prime: Optional[int] = None
        n_witness: Optional[int] = None
        witness_values: Dict[int, FieldElement] = {}

        for _ in range(num_sections):
            sec_hdr = self.stream.read(12)
            if len(sec_hdr) < 12:
                break
            sec_type, sec_size = struct.unpack("<IQ", sec_hdr)
            sec_start = self.stream.tell()

            if sec_type == SECTION_WTNS_HEADER:
                field_size_bytes = self.stream.read(4)
                field_size = struct.unpack("<I", field_size_bytes)[0]
                prime_bytes = self.stream.read(field_size)
                prime = int.from_bytes(prime_bytes, byteorder="little")
                n_witness_bytes = self.stream.read(4)
                n_witness = struct.unpack("<I", n_witness_bytes)[0]
            elif sec_type == SECTION_WTNS_DATA:
                if field_size is None or prime is None or n_witness is None:
                    raise ValueError("WTNS Data section appeared before Header section")
                for wid in range(n_witness):
                    val_bytes = self.stream.read(field_size)
                    if len(val_bytes) < field_size:
                        raise ValueError(f"Unexpected EOF reading witness element {wid}")
                    val_int = int.from_bytes(val_bytes, byteorder="little")
                    witness_values[wid] = FieldElement(val_int, modulus=prime)
            else:
                self.stream.seek(sec_start + sec_size)

        if prime is None:
            prime = BN254_PRIME

        return Witness(values=witness_values, modulus=prime)


class WTNSBinaryWriter:
    """Serializes a Witness object into the official Circom binary .wtns format."""

    @classmethod
    def to_bytes(cls, witness: Witness, field_size: int = 32) -> bytes:
        buf = io.BytesIO()
        writer = cls(witness, buf, field_size=field_size)
        writer.write()
        return buf.getvalue()

    @classmethod
    def to_file(cls, witness: Witness, path: Union[str, Path], field_size: int = 32) -> None:
        with open(path, "wb") as f:
            writer = cls(witness, f, field_size=field_size)
            writer.write()

    def __init__(self, witness: Witness, stream: BinaryIO, field_size: int = 32) -> None:
        self.witness = witness
        self.stream = stream
        self.field_size = field_size

    def write(self) -> None:
        # Magic
        self.stream.write(WTNS_MAGIC)
        # Version 2
        self.stream.write(struct.pack("<I", 2))
        # 2 sections
        self.stream.write(struct.pack("<I", 2))

        # --- Section 1: Header ---
        ordered_list = self.witness.to_list()
        n_witness = len(ordered_list)

        header_buf = io.BytesIO()
        header_buf.write(struct.pack("<I", self.field_size))
        header_buf.write(self.witness.modulus.to_bytes(self.field_size, byteorder="little"))
        header_buf.write(struct.pack("<I", n_witness))
        header_data = header_buf.getvalue()

        self.stream.write(struct.pack("<IQ", SECTION_WTNS_HEADER, len(header_data)))
        self.stream.write(header_data)

        # --- Section 2: Data ---
        data_buf = io.BytesIO()
        for elem in ordered_list:
            data_buf.write(elem.to_bytes(length=self.field_size, byteorder="little"))
        data_bytes = data_buf.getvalue()

        self.stream.write(struct.pack("<IQ", SECTION_WTNS_DATA, len(data_bytes)))
        self.stream.write(data_bytes)


class SymbolTableParser:
    """Parses Circom .sym files mapping wire indexes to signal paths."""

    @classmethod
    def from_file(cls, path: Union[str, Path]) -> Dict[int, str]:
        with open(path, "r", encoding="utf-8") as f:
            return cls.from_string(f.read())

    @classmethod
    def from_string(cls, content: str) -> Dict[int, str]:
        symbols: Dict[int, str] = {}
        for line in content.splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = [p.strip() for p in line.split(",")]
            if len(parts) >= 2:
                try:
                    wire_id = int(parts[0])
                    symbol_name = parts[1]
                    symbols[wire_id] = symbol_name
                except ValueError:
                    continue
        return symbols


class JSONWitnessParser:
    """Parses JSON formatted witness files."""

    @classmethod
    def from_file(cls, path: Union[str, Path], modulus: int = BN254_PRIME) -> Witness:
        with open(path, "r", encoding="utf-8") as f:
            return cls.from_string(f.read(), modulus=modulus)

    @classmethod
    def from_string(cls, content: str, modulus: int = BN254_PRIME) -> Witness:
        data = json.loads(content)
        witness_dict: Dict[int, FieldElement] = {}

        if isinstance(data, list):
            for i, val in enumerate(data):
                witness_dict[i] = FieldElement(val, modulus=modulus)
        elif isinstance(data, dict):
            for k, val in data.items():
                try:
                    wire_id = int(k)
                    witness_dict[wire_id] = FieldElement(val, modulus=modulus)
                except ValueError:
                    # Ignore non-integer keys or symbols in raw witness mapping
                    pass
        else:
            raise ValueError(f"Expected JSON array or object for witness, got {type(data).__name__}")

        return Witness(values=witness_dict, modulus=modulus)
